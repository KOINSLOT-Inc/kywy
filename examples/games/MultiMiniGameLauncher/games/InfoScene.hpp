// Bitmap Constants
#define KYWY_QR_WIDTH 128
#define KYWY_QR_HEIGHT 128

class InfoScene : public Scene {
private:
  // Actor to handle input
  class InputHandler : public Actor::Actor {
  private:
    InfoScene* scene;
  public:
    InputHandler(InfoScene* s)
      : Actor::Actor(), scene(s) {
      scene->Scene::add(this, false);
    }

    void handle(::Actor::Message* message) {
      if (!scene->isActive()) return;
      switch (message->signal) {
        case Kywy::Events::BUTTON_LEFT_PRESSED:
          scene->triggerExit();
          return;
        default:
          break;
      }
    }
  } inputHandler{ this };

public:
  InfoScene()
    : Scene(true), inputHandler(this) {}

  void onEnter() override {
    updateDisplay();
  }

  void updateDisplay() {
    Display::Display& display = Scene::getEngine()->display;
    display.clear();

    // Draw QR centered
    int qrX = (KYWY_DISPLAY_WIDTH - KYWY_QR_WIDTH) / 2;
    int qrY = 6;
    display.drawBitmap(qrX, qrY, KYWY_QR_WIDTH, KYWY_QR_HEIGHT, (uint8_t*)kywy_qr_data);

    // Draw label below QR
    display.drawText(KYWY_DISPLAY_WIDTH / 2, qrY + KYWY_QR_HEIGHT + 8, "kywy.io",
                     Display::TextOptions().origin(Display::Origin::Text::CENTER));

    // Instructions
    display.drawText(KYWY_DISPLAY_WIDTH / 2, qrY + KYWY_QR_HEIGHT + 20, "Press LEFT to return",
                     Display::TextOptions().origin(Display::Origin::Text::CENTER));

    display.update();
  }
};

